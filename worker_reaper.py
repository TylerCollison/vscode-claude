#!/usr/bin/env python3
"""Worker Reaper — remove dispatched workers once they have run to completion.

Dispatched worker containers/services (beads workers and MR/PR responders) are
created with `--restart no` / `--restart-condition none`, so they run to
completion and never come back — but their Swarm services and local containers
linger on the node forever. This daemon periodically reconciles that
accumulation.

Mode
---
  * swarm manager node -> reconciles `docker service` objects
  * otherwise          -> reconciles local containers (`docker ps -a`)

Each cycle re-detects the mode, matching how the dispatchers dispatch today.

The safety property (the whole point of the seen-up set)
--------------------------------------------------------
A worker is removed ONLY when both are true:

  1. the reaper previously observed that specific worker UP (a running task, or
     a running container in local mode), and
  2. it is now observed DOWN — the service has no running tasks, or the local
     container has exited.

Workers don't restart, so seen-up-then-down means the worker ran to completion
(or definitively died). A worker that has never been observed UP is NEVER
removed: a freshly created service's task may not have started yet, and a
container may be sitting in `created` — deleting either would kill work before
it begins. That constraint also makes the created-but-not-started race
mid-scan harmless: a worker dispatched while the reaper is scanning simply
isn't in the enumeration, so it cannot be touched until it is seen UP in a
later cycle.

State
-----
Observation state lives in a JSON file under WORKER_REAPER_STATE_DIR (default
`/config/.worker-reaper`), on the same persistent mount as the dispatchers'
seen-set state dirs, so it survives a container restart: without it, a restart
would forget every worker had been observed UP and could never reap them (or,
worse, re-decide about them from scratch). Entries for workers that no longer
exist are dropped, tolerating out-of-band removal.

Worker identification
---------------------
Workers are recognized by dispatch labels at dispatch time
(`dispatch.worker=true`, plus the per-dispatcher id labels) rather than by
name alone. For workers dispatched before labeling existed, the name prefix
plus the guaranteed 20-digit timestamp suffix (`beads-*` / `mr-pr-*` names
end in `-YYYYMMDDhhmmssuuuuuu`, generated by the dispatchers' worker_name())
is used as a fallback — the dispatcher containers themselves and other node
residents never carry that shape. Swarm task containers seen in local mode
are never touched: their lifecycle belongs to the service, which a swarm
manager's reaper removes via `docker service rm`.

Stdlib only (no pip deps): shells out to the `docker` CLI, like the dispatchers.
"""

import json
import os
import re
import shutil
import signal
import sys
import threading
import time

import dispatch_utils as du

# Names the dispatchers give workers (see worker_name() in beads_dispatch.py /
# mr_pr_dispatch.py): a `beads-` / `mr-pr-` prefix, a slug/id portion, and a
# timestamp suffix of exactly 20 digits that guarantees uniqueness.
WORKER_NAME_RE = re.compile(r"^(?:beads|mr-pr)-.+-[0-9]{20}$")

# Label the dispatchers stamp on every dispatched worker (shared constant).
WORKER_LABEL = du.WORKER_LABEL

# Swarm sets this label on every task container. Containers carrying it are not
# local-mode workers: removing them out from under the service they belong to
# is not this daemon's job (the manager reaps the service itself).
SWARM_SERVICE_LABEL = "com.docker.swarm.service.name"

DOCKER_SOCKET_PATHS = ("/var/run/docker.sock", "/run/docker.sock")


class Config:
    def __init__(self):
        self.interval = int(du.env("WORKER_REAPER_INTERVAL", "60"))
        self.state_dir = du.env("WORKER_REAPER_STATE_DIR", "/config/.worker-reaper")


def state_path(cfg):
    return os.path.join(cfg.state_dir, "state.json")


# --------------------------------------------------------------------------- state


def load_reaper_state(path):
    """Load {worker_name: first_seen_up_unix_ts} from the state file."""
    try:
        with open(path) as fh:
            data = json.load(fh)
        seen = data.get("seen_up", {})
        if isinstance(seen, dict):
            return {str(name): value for name, value in seen.items()}
    except (OSError, ValueError):
        pass
    return {}


def save_reaper_state(path, seen_up):
    """Persist {worker_name: first_seen_up_unix_ts} atomically (tmp + replace)."""
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "w") as fh:
            json.dump({"seen_up": seen_up}, fh, sort_keys=True)
        os.replace(tmp, path)
    except OSError as e:
        du.log("WARNING: could not persist reaper state: %s" % e)


# --------------------------------------------------------------------------- identification


def is_worker(name, labels=None):
    """True when a docker object is a worker dispatched by a fleet node.

    Trusted first: dispatch labels (`dispatch.worker`, `mr_pr.id`, ...), which
    the dispatchers stamp on every worker. Fallback for workers dispatched
    before labeling existed: the worker name pattern (prefix + 20-digit
    timestamp suffix), which node residents and the dispatcher itself never
    match.
    """
    labels = labels or {}
    if str(labels.get(WORKER_LABEL, "")) == "true":
        return True
    if any(key == "mr_pr.id" or key.startswith("beads.") for key in labels):
        return True
    return bool(WORKER_NAME_RE.match(name or ""))


def replicas_running(replicas):
    """Running count out of a `docker service ls` `{{.Replicas}}` value.

    "<running>/<desired>" — returns the running part (0 when unparseable).
    """
    running = (replicas or "").split("/")[0].strip()
    try:
        return int(running)
    except ValueError:
        return 0


# --------------------------------------------------------------------------- enumeration


def list_swarm_workers():
    """Return {service_name: running_bool} for dispatched-worker services.

    None means "could not enumerate" (docker unavailable / not a manager); the
    caller must skip the cycle rather than guess.
    """
    # One pass over all services, matched by worker name pattern ...
    rc, out, err = du.run(["docker", "service", "ls",
                           "--format", "{{.Name}}\t{{.Replicas}}"])
    if rc != 0:
        return None
    found = {}
    for line in out.splitlines():
        name, _, replicas = line.partition("\t")
        if name and is_worker(name):
            found[name] = replicas_running(replicas) > 0
    # ... unioned with label-tagged services, so workers are recognized even
    # if a future dispatcher changes its naming scheme.
    rc, out, _ = du.run(["docker", "service", "ls",
                         "--filter", "label=%s=true" % WORKER_LABEL,
                         "--format", "{{.Name}}\t{{.Replicas}}"])
    if rc == 0:
        for line in out.splitlines():
            name, _, replicas = line.partition("\t")
            if name:
                found[name] = replicas_running(replicas) > 0
    return found


def swarm_service_running(name):
    """True/False by task state, or None when it cannot be determined."""
    rc, out, _ = du.run(["docker", "service", "ps", name,
                         "--format", "{{.CurrentState}}"])
    if rc != 0:
        return None
    states = [state.strip() for state in out.splitlines() if state.strip()]
    return any(state == "Running" for state in states)


def list_local_workers():
    """Return {container_name: running_bool} for local dispatched workers.

    None means "could not enumerate" (docker unavailable).
    """
    # One pass over all containers; the two identification labels are read
    # inline so no per-container inspect is needed.
    fmt = ("{{.Names}}\t{{.State}}\t{{.Label \"%s\"}}\t{{.Label \"mr_pr.id\"}}"
           "\t{{.Label \"%s\"}}") % (WORKER_LABEL, SWARM_SERVICE_LABEL)
    rc, out, err = du.run(["docker", "ps", "-a", "--format", fmt])
    if rc != 0:
        return None
    found = {}
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) != 5:
            continue
        name, state, worker_label, mr_pr_label, swarm_service = parts
        if swarm_service:
            # Swarm task container: lifecycle owned by its service, which a
            # swarm manager's reaper reaps. Never rm it from under the service.
            continue
        labels = {}
        if worker_label:
            labels[WORKER_LABEL] = worker_label
        if mr_pr_label:
            labels["mr_pr.id"] = mr_pr_label
        if not is_worker(name, labels):
            continue
        found[name] = state == "running"
    return found


# --------------------------------------------------------------------------- removal


def remove_worker(name, swarm):
    """Remove a completed worker. Returns (removed, already_gone).

    already_gone means the removal achieved its effect out-of-band (someone
    else rm'd it first): the caller drops the state entry either way.
    """
    if swarm:
        rc, out, err = du.run(["docker", "service", "rm", name])
    else:
        rc, out, err = du.run(["docker", "rm", name])
    if rc == 0:
        return True, False
    msg = (err or out).lower()
    if "no such" in msg or "not found" in msg:
        return False, True
    du.log("WARNING: removal failed for worker %s: %s" % (name, err or out))
    return False, False


# --------------------------------------------------------------------------- cycle


def reap_cycle(cfg, swarm):
    """One reconciliation pass. Returns a summary dict."""
    path = state_path(cfg)
    seen_up = load_reaper_state(path)

    if swarm:
        workers = list_swarm_workers()
    else:
        workers = list_local_workers()
    if workers is None:
        du.log("WARNING: could not enumerate workers (docker socket unavailable?) — skipping this cycle.")
        return {"skipped": True}

    now = int(time.time())
    changed = False
    removed = []
    for name in sorted(workers):
        running = workers[name]
        if not running and swarm:
            # The service-ls replicas snapshot can lag (or drift in format):
            # confirm by task state before acting on a down-looking worker.
            verified = swarm_service_running(name)
            if verified is None:
                du.log("WARNING: could not verify task state for worker %s — retrying next cycle." % name)
                continue
            running = verified
        if running:
            # Observed UP: record the first time we saw it (kept stable
            # across cycles) so a later DOWN observation can reap it.
            if name not in seen_up:
                seen_up[name] = now
                changed = True
                du.log("Observed worker %s UP — recorded for later reaping." % name)
            continue
        if name not in seen_up:
            # Never observed UP (created-but-not-started, or it finished faster
            # than one interval). Preserving it is the safe failure mode.
            continue
        # Seen UP before, now DOWN: remove (never force-kill a worker that
        # came back up between the check and the rm — the removal is retried).
        ok, already_gone = remove_worker(name, swarm)
        if ok or already_gone:
            seen_at = time.strftime("%Y-%m-%d %H:%M:%S",
                                    time.localtime(seen_up.get(name, now)))
            del seen_up[name]
            changed = True
            removed.append(name)
            du.log("Reaped worker %s (%s) — observed up at %s, now down; ran to completion."
                   % (name, "service" if swarm else "container", seen_at))
        # else: removal failed — keep the entry and retry next cycle.

    # Out-of-band removal tolerance: drop entries for workers that no longer
    # exist on this node at all.
    for name in list(seen_up):
        if name not in workers:
            del seen_up[name]
            changed = True

    if changed:
        save_reaper_state(path, seen_up)
    return {"removed": removed, "seen_up": len(seen_up), "workers": len(workers)}


def run_daemon(cfg):
    """Periodically reap completed workers; exits on SIGTERM/SIGINT."""
    stop = threading.Event()

    def _sig(_signum, _frame):
        stop.set()

    signal.signal(signal.SIGTERM, _sig)
    signal.signal(signal.SIGINT, _sig)

    du.log("Worker reaper daemon running (interval=%ds, state=%s)."
           % (cfg.interval, state_path(cfg)))
    mode = None
    while not stop.is_set():
        try:
            swarm = du.is_swarm_manager()
            if swarm != mode:
                mode = swarm
                du.log("Reaper mode: %s." % ("swarm (docker service)" if swarm else "local (docker containers)"))
            reap_cycle(cfg, swarm)
        except Exception as e:
            du.log("ERROR: unexpected error during reap cycle: %s" % e)
        if not stop.is_set():
            stop.wait(cfg.interval)
    du.log("Worker reaper daemon stopped.")
    return 0


def main(argv):
    cfg = Config()

    if du.env("WORKER_REAPER") != "true":
        du.log("Worker reaper not enabled (WORKER_REAPER is not 'true'). Exiting.")
        return 0

    if not shutil.which("docker"):
        du.log("WARNING: docker not found on PATH. Exiting.")
        return 0

    # Check for docker socket at both common locations
    docker_sock = None
    for sock in DOCKER_SOCKET_PATHS:
        if os.path.exists(sock):
            docker_sock = sock
            break
    if not docker_sock:
        du.log("WARNING: Docker socket not found at /var/run/docker.sock or /run/docker.sock. Exiting.")
        return 0

    if "--once" in argv:
        reap_cycle(cfg, du.is_swarm_manager())
        du.log("One-shot reap cycle complete.")
        return 0

    return run_daemon(cfg)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
